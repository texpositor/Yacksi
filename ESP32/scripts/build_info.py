# PlatformIO pre-build script: writes src/BuildInfo.cpp with the build time and
# git revision on every build, so the firmware can report exactly which build
# is running. Only that small file is recompiled when nothing else changed.
Import("env")

import datetime
import os
import subprocess


def git(*args):
    try:
        return subprocess.check_output(
            ["git", *args], cwd=env.subst("$PROJECT_DIR"),
            stderr=subprocess.DEVNULL, text=True).strip()
    except Exception:
        return "unknown"


stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
revision = git("describe", "--always", "--dirty")
path = os.path.join(env.subst("$PROJECT_SRC_DIR"), "BuildInfo.cpp")
with open(path, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_info.py on every build; do not edit.\n"
            '#include "Calibration.h"\n\n'
            f'const char* const BUILD_TIME = "{stamp}";\n'
            f'const char* const BUILD_GIT = "{revision}";\n')
